export function translate(
  key: string,
  language: Language,
  values: Record<string, string | number> = {},
): string {
  const text = language === 'ru' ? (russian[key] ?? key) : key
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    values[name] === undefined ? match : String(values[name]),
  )
}
